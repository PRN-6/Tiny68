impl PixelBuffer {
    /// Renders a semi-transparent colored box for HUD background
    pub fn fill_rect_alpha(&mut self, rx: i32, ry: i32, rw: u32, rh: u32, color_bgra: u32) {
        let x0 = rx.max(0) as u32;
        let y0 = ry.max(0) as u32;
        let x1 = ((rx + rw as i32).max(0) as u32).min(self.width);
        let y1 = ((ry + rh as i32).max(0) as u32).min(self.height);

        for y in y0..y1 {
            let row = (y as usize) * (self.width as usize);
            for x in x0..x1 {
                self.pixels[row + (x as usize)] = color_bgra;
            }
        }
    }

    /// Renders a single character using the 5x7 bitmap font
    pub fn draw_char(&mut self, cx: i32, cy: i32, c: char, color_bgra: u32) {
        let bits = glyph_bits(c);
        for (row_idx, &row_byte) in bits.iter().enumerate() {
            let py = cy + row_idx as i32;
            if py < 0 || py >= self.height as i32 {
                continue;
            }
            let row_offset = (py as usize) * (self.width as usize);
            for col_idx in 0..5 {
                if (row_byte & (1 << (4 - col_idx))) != 0 {
                    let px = cx + col_idx;
                    if px >= 0 && px < self.width as i32 {
                        self.pixels[row_offset + (px as usize)] = color_bgra;
                    }
                }
            }
        }
    }

    /// Renders a string of text using the 5x7 bitmap font
    pub fn draw_text(&mut self, mut x: i32, y: i32, text: &str, color_bgra: u32) {
        for ch in text.chars() {
            self.draw_char(x, y, ch, color_bgra);
            x += 6; // 5 px width + 1 px spacing
        }
    }

    /// Renders the complete diagnostics HUD overlay box
    pub fn draw_diagnostics_hud(&mut self, start_x: i32, start_y: i32, lines: &[&str]) {
        let box_w = 260u32;
        let line_h = 12i32;
        let box_h = ((lines.len() as i32) * line_h + 16) as u32;

        // Dark translucent background: BGRA with ~80% alpha premultiplied
        // Alpha = 200 (0xC8). RGB = (20, 22, 28) -> Premultiplied = (15, 17, 22)
        let bg_color = 0xC8_16_11_0F;
        self.fill_rect_alpha(start_x, start_y, box_w, box_h, bg_color);

        // Header accent line
        let mint_accent = 0xFF_57_CC_99;
        self.fill_rect_alpha(start_x, start_y, box_w, 2, mint_accent);

        let mut curr_y = start_y + 8;
        let text_color = 0xFF_F0_F0_F0;

        for line in lines {
            self.draw_text(start_x + 8, curr_y, line, text_color);
            curr_y += line_h;
        }
    }
}
